def read_jsonl(path):
    with open(path, encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def is_total(r):
    return all(r.get(k, "ALL") == "ALL" for k in ("gender", "age_bucket", "race_or_ethnicity"))


def long_date(iso):
    return dt.date.fromisoformat(iso).strftime("%B %d, %Y").replace(" 0", " ")


def month_year(d):
    return d.strftime("%B %Y")


def pct(x):
    return f"{x:.0%}"


def entries_ts(entries):
    def one(e):
        group = f", group: {json.dumps(e['group'])}" if e.get("group") else ""
        return f"        {{ id: {json.dumps(e['id'])}, label: {json.dumps(e['label'])}{group} }}"
    return ",\n".join(one(e) for e in entries) + ","


def main(repo):
    clean = os.path.join(repo, "fl-data", "clean")
    v = {}

    with open(os.path.join(clean, "prison_localities.json"), encoding="utf-8") as f:
        prison_entries = json.load(f)
    with open(os.path.join(clean, "supervision_localities.json"), encoding="utf-8") as f:
        offices = json.load(f)

    totals = {}
    for r in read_jsonl(os.path.join(clean, "incarceration_population_by_facility_by_demographics.json")):
        if r["facility"] == "ALL" and r["gender"] == "ALL" and r["age_bucket"] == "ALL":
            totals[r["race_or_ethnicity"]] = int(r["total_population"])
            as_of = r["date_of_stay"]
    total = totals["ALL"]
    major = next(int(r["total_population"]) for r in read_jsonl(os.path.join(
        clean, "incarceration_population_by_facility_by_demographics.json"))
        if r["facility"] == "GROUP_MAJOR_PRISONS" and is_total(r))
    major_count = sum(1 for e in prison_entries
                      if e.get("group") == "Major prisons" and not e["id"].startswith("GROUP_"))
    v.update(AS_OF_LONG=long_date(as_of), TOTAL=f"{total:,}", ASIAN=f"{totals['ASIAN']:,}",
             MAJOR_PCT=pct(major / total), MAJOR_COUNT=str(major_count))

    pop = sorted((dt.date.fromisoformat(r["population_date"]), int(r["population_count"]))
                 for r in read_jsonl(os.path.join(clean, "incarceration_population_by_month_by_demographics.json"))
                 if is_total(r))
    peak = max(pop, key=lambda p: p[1])
    low = min((p for p in pop if p[0] > peak[0]), key=lambda p: p[1])
    v.update(POP_FIRST_DATE=long_date(pop[0][0].isoformat()), POP_FIRST=f"{pop[0][1]:,}",
             POP_PEAK=f"{peak[1]:,}", POP_PEAK_DATE=month_year(peak[0]),
             POP_LOW=f"{low[1]:,}", POP_LOW_DATE=month_year(low[0]), TOTAL_MONTH=f"{pop[-1][1]:,}")

    stay = next(r for r in read_jsonl(os.path.join(clean, "incarceration_lengths_by_demographics.json")) if is_total(r))
    n = int(stay["total_release_count"])
    v.update(STAY_TOTAL=f"{n:,}", STAY_UNDER1=pct(int(stay["years_0_1"]) / n),
             STAY_OVER5=pct(sum(int(stay[k]) for k in ("years_5_10", "years_10_20", "years_20_plus")) / n))

    rec3 = {int(r["release_cohort"]): float(r["recidivism_rate"])
            for r in read_jsonl(os.path.join(clean, "recidivism_rates_by_cohort_by_year.json"))
            if is_total(r) and r["followup_years"] == "3"}
    latest = max(rec3)
    v.update(REC_LATEST3_COHORT=str(latest), REC_LATEST3=pct(rec3[latest]),
             REC3_MIN=pct(min(rec3.values())), REC3_MAX=pct(max(rec3.values())),
             REC3_FIRST_COHORT=str(min(rec3)))

    sup = read_jsonl(os.path.join(clean, "supervision_population_by_district_by_demographics.json"))
    tot = {(r["supervision_type"], r["district"]): int(r["total_supervision_count"]) for r in sup if is_total(r)}
    label = {e["id"]: e["label"] for e in offices}
    top = max((o for (t, o) in tot if t == "PROBATION" and o != "ALL"), key=lambda o: tot[("PROBATION", o)])
    v.update(PROB_TOTAL=f"{tot[('PROBATION', 'ALL')]:,}", PAROLE_TOTAL=f"{tot[('PAROLE', 'ALL')]:,}",
             PROB_TOP_OFFICE=label[top], PROB_TOP_COUNT=f"{tot[('PROBATION', top)]:,}")
    with open(os.path.join(clean, "real_metrics_report.txt"), encoding="utf-8") as f:
        sup_as_of = next(line for line in f if "Supervision records" in line).rsplit(": ", 1)[1].strip()
    v["SUP_AS_OF_LONG"] = long_date(sup_as_of)

    # Supervision type counts for the parole page copy (recount from raw-free clean data is not
    # possible, so read the documented counts in DATA_NOTES-friendly form from the raw profile)
    sup_types = os.path.join(clean, "supervision_type_counts.json")
    with open(sup_types, encoding="utf-8") as f:
        types = json.load(f)
    v.update(CR_TOTAL=f"{types['CONDITIONAL REL.SUPERVISN']:,}", PAROLE_STATE=f"{types['PAROLE STATE']:,}")

    with open(os.path.join(clean, "real_inputs_racial_disparities.json"), encoding="utf-8") as f:
        rd = json.load(f)
    state_all = rd["ALL"]["total_state_population"]
    fdc_all = rd["ALL"]["current_total_sentenced_count"]
    v.update(BLACK_STATE=pct(rd["BLACK"]["total_state_population"] / state_all),
             BLACK_FDC=pct(rd["BLACK"]["current_total_sentenced_count"] / fdc_all),
             HISP_STATE=pct(rd["HISPANIC"]["total_state_population"] / state_all),
             HISP_FDC=pct(rd["HISPANIC"]["current_total_sentenced_count"] / fdc_all))

    out = TEMPLATE.replace("__ENTRIES__", entries_ts(prison_entries)).replace("__OFFICES__", entries_ts(offices))
    out = HEADER + out
    for key, val in v.items():
        out = out.replace(f"__{key}__", val)
    leftover = [w for w in out.split("__") if w.isupper() and w.replace("_", "").isalnum()]
    if leftover:
        sys.exit(f"unfilled placeholders: {leftover}")
    path = os.path.join(repo, "spotlight-client", "src", "contentApi", "sources", "us_fl.ts")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
    print(f"wrote {path}")
